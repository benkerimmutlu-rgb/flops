export function getCluster(id: string): Cluster | undefined {
  return CLUSTERS.find((c) => c.id === id);
}

export function getTopic(topicId: string): { cluster: Cluster; topic: Topic } | undefined {
  for (const cluster of CLUSTERS) {
    const topic = cluster.topics.find((t) => t.id === topicId);
    if (topic) return { cluster, topic };
  }
  return undefined;
}

